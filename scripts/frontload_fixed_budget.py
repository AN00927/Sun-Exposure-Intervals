    ax.set_title("ARM (b) peak dose, %g SED/wk budget" % budget)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig("%s/frontload_safety.png" % FIG_DIR, dpi=130)
    plt.close(fig)


