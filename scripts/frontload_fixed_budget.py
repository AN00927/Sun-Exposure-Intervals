"""Front-loading vs splitting a FIXED UV budget -- deterministic grid sweep.

The advisor's question, verbatim
-------------------------------
    "For fixed total exposure time per week (say -- or per month if you
    prefer), is it better to front load rather than split time across days?
    (your exponential decay models). Let's answer these questions carefully
    with just melanin dynamics. Then, later, we can add skin thickening. And
    then add skin cancer risk. The answers should be quantitative, with plots
    if possible."

That question conflates two different things, and separating them is most of
the work. This script answers both, labelled separately:

ARM (a) -- WITHIN-WEEK CONCENTRATION
    The weekly SED budget is held fixed and only the number of days it is
    spread over changes: 7 small sessions ... 1 large session. This is
    literally "front load rather than split time across days". The pattern
    repeats every week for the whole horizon, so nothing is front-loaded
    across the horizon -- only within each week.

ARM (b) -- ACROSS-HORIZON TAPER
    The TOTAL SED over the whole horizon is held fixed and the dose profile is
    varied from flat to front-loaded-and-tapering (the "exponential decay
    models"), crossed with session spacing warped by `warp_days(gamma)`
    (gamma = 1 uniform, > 1 front-loaded, < 1 back-loaded). Dose shapes are
    generated by the existing `vitd_optimization` families and then rescaled so
    every arm delivers exactly the same total SED.

Mechanism ladder
----------------
Every arm is run at all three rungs of `vitd_ablation` -- `melanin_only` (the
advisor's step 1, and the PRIMARY arm here), `melanin_plus_sc` (the "then add
skin thickening" contrast), and `melanin_sc_risk`. Read `vitd_ablation`'s
docstring for the caveats; two of them constrain how this output may be read:

  * `melanin_only` is an ABLATION, not a re-fit. Absolute 25(OH)D under it is a
    mechanism-isolation diagnostic. Only WITHIN-rung schedule rankings are
    defensible, so the headline figure plots each arm RELATIVE to its own
    rung's reference schedule, and the absolute-level figure keeps the rungs in
    separate panels.
  * `melanin_sc_risk` is dynamically IDENTICAL to `melanin_plus_sc`. It is a
    REPORTING rung: it obliges the analysis to show the skin-cancer indices
    that `simulate()` computes on every call anyway. It is not "cancer risk
    added to the model".

Method
------
DETERMINISTIC GRID SEARCH, no stochastic optimiser and NO constraint applied.
The risk-constrained joint optimisers in `vitd_optimization` are deliberately
not used: they impose a sufficiency floor and an erythema cap, which would
silently delete exactly the concentrated arms this question is about, and their
single-seed results are documented as several percent unstable.

Because no cap is applied, a concentrated arm can demand a single session far
above the erythema threshold. Every row therefore carries the maximum single
session dose as a fraction of MED (via `vitd_model.compute_safety_sidecar`),
compared against `vitd_objectives.GAMMA_MED` (sub-erythemal ceiling) and
against 1.0 MED (frank burn). Infeasible arms are flagged in the CSV, in the
console summary, and on the plots. An arm that "wins" while requiring a burn
has not won.

Thresholds come from `vitd_objectives`; parameter values are never restated
here -- see the `vitd_model` module docstring, the only canonical source.

Horizon, and the metric conflict it exposes
-------------------------------------------
Arm (a) runs at `vitd_analyses.PROTOCOL_DAYS` only: its mechanism is
per-session dose saturation, which does not care how long the protocol runs.
Arm (b) runs at that horizon AND at 365 d, because at 84 d the three-parameter
dose families barely have room to express a shape and a null result there
alone invites the rebuttal "you did not give them room to work". The horizon is
threaded through as a parameter; `PROTOCOL_DAYS` is read and never rebound,
because other analyses depend on it and RESULTS.md section 5 comparability
rests on 84 d.

Running the longer horizon surfaced something that matters more than the taper
result itself: the outcome measures split into two camps that disagree about
the SIGN of the taper, and the disagreement WIDENS with the horizon.

  TERMINAL measures -- `steady_state_D` (mean over the last 28 d) and
  `final_D` (the endpoint) -- reward putting dose next to the measurement
  window. At 365 d they are maximised by the most BACK-loaded spacing on the
  grid, which opens with a ~48-day gap of no exposure at all and then ramps to
  near-daily dosing over the final month.

  INTEGRATED measures -- deficit AUC below sufficiency, and time to
  sufficiency -- score the whole horizon. They are maximised by FRONT-loaded
  spacing, and they rate that same back-loaded schedule as roughly an order of
  magnitude worse.

So a taper "gain" read off a terminal metric at a long horizon is an artefact
of where the ruler is held, not a property of the schedule. `steady_state_D`
is a defensible ranking metric at 84 d, where the averaging window is a third
of the horizon; it is NOT one at 365 d. Every arm therefore carries
`max_gap_days`, `first_gap_days` and `days_to_sufficiency` so a spacing
exponent that "wins" by leaving the front of the horizon empty is visible as
such, and `figs/frontload_taper_metric_conflict.png` plots both camps together
so neither can be quoted alone.

What arm (b) concludes, and on which metric
------------------------------------------
CONCLUSION. The plateau is set by the weekly budget and by how finely it is
split -- that is arm (a) -- and its ARRANGEMENT over the horizon does not move
it. What front-loading buys is the TRANSIENT: reaching sufficiency fast and
minimising accumulated deficiency on the way.

Arm (b) is therefore ranked on the time-integrated deficiency burden
(`AUC_deficit_below_sufficiency`, minimised), with the plateau
(`steady_state_D`) reported alongside as a SECONDARY. See the RANKING_METRIC
block below the constants for the two reasons -- the 365-day co-movement
evidence, and alignment with the PRIMARY objective already fixed in
`vitd_objectives.OBJECTIVE_HIERARCHY`. The plateau is never deleted or hidden,
so the earlier plateau-ranked framing stays reproducible.

Both results matter and neither may be dropped:

  THE NULL (plateau). Matched-N, restricted to the front-loaded half of the
  grid, front-loading gains a mean +0.43% at 84 d and +0.00% at 365 d. Giving
  the shape families four times the room made the null cleaner, not weaker.

  THE RESULT (transient). Matched-N, the same schedules cut the deficiency
  burden by a mean 49% at 84 d and 69% at 365 d (44.8% / 65.1% once the
  sub-erythemal ceiling is imposed), with optimal gamma front-loaded at both
  horizons. Time to sufficiency at the deficit optimum is ~21 d against ~249 d
  at the plateau optimum.

ARTEFACT -- do not quote the raw plateau maximum. Over the whole grid at 365 d
the largest plateau "gain" is +19.4%, and it is won by maximal BACK-loading.
That arm opens with a ~48-day gap of no exposure at all, then ramps to
near-daily dosing across the final month: it stacks dose under the measurement
window. It carries a deficit of 4976 nmol/L.d against 2360 for flat + uniform
spacing, and reaches sufficiency on day 251 against day 21. It is a
terminal-metric artefact, not a schedule, and the console summary, the CSV
columns (`max_gap_days`, `first_gap_days`, `days_to_sufficiency`) and
`figs/frontload_taper_metric_conflict.png` all exist to make that visible.

Outputs
-------
    tables/frontload_within_week.csv                  arm (a)
    tables/frontload_horizon_taper.csv                arm (b), 84 d
    tables/frontload_horizon_taper_365d.csv           arm (b), 365 d
    tables/frontload_taper_horizon_comparison.csv     matched-N, both horizons
    figs/frontload_within_week.png
    figs/frontload_within_week_absolute.png
    figs/frontload_horizon_taper.png
    figs/frontload_horizon_taper_365d.png
    figs/frontload_taper_metric_conflict.png
    figs/frontload_safety.png
"""

