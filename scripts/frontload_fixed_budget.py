def run(params: Optional[ModelParams] = None,
        taper_horizons: Sequence[int] = TAPER_HORIZONS) -> pd.DataFrame:
    """Run both arms, write tables + figures, return the combined DataFrame.

    Arm (a) runs at `HORIZON_DAYS` only -- its mechanism is per-session dose
    saturation, which does not depend on how long the protocol runs. Arm (b)
    runs at every horizon in `taper_horizons`, because the taper question is
    intrinsically a longer-horizon one: at 84 d the three-parameter dose
    families have very little room to express a shape.
    """
    os.makedirs(FIG_DIR, exist_ok=True)
    os.makedirs(TAB_DIR, exist_ok=True)

    df_a = sweep_within_week(params, HORIZON_DAYS)
    df_a.to_csv("%s/frontload_within_week.csv" % TAB_DIR, index=False)
    _plot_within_week(df_a)
    _plot_within_week_absolute(df_a)
    _summarise_within_week(df_a)

    frames: Dict[int, pd.DataFrame] = {}
    written: List[str] = []
    for horizon in taper_horizons:
        suffix = "" if horizon == HORIZON_DAYS else "_%dd" % horizon
        df_h = sweep_horizon_taper(params, horizon)
        path = "%s/frontload_horizon_taper%s.csv" % (TAB_DIR, suffix)
        df_h.to_csv(path, index=False)
        written.append("%s (%d rows, horizon %d d)" % (path, len(df_h), horizon))
        _plot_horizon_taper(df_h, horizon, suffix)
        if horizon == HORIZON_DAYS:
            _plot_safety(df_a, df_h, horizon)
        _summarise_taper(df_h, horizon)
        frames[horizon] = df_h

    _plot_metric_conflict(frames)
    cmp_df = taper_horizon_comparison(frames)
    cmp_path = "%s/frontload_taper_horizon_comparison.csv" % TAB_DIR
    cmp_df.to_csv(cmp_path, index=False)
    _summarise_horizon_comparison(cmp_df)

    _summarise_risk(df_a)

    print("\n  Wrote %s/frontload_within_week.csv (%d rows)"
          % (TAB_DIR, len(df_a)))
    for w in written:
        print("  Wrote %s" % w)
    print("  Wrote %s (%d rows)" % (cmp_path, len(cmp_df)))
    figs = ["frontload_within_week", "frontload_within_week_absolute",
            "frontload_safety", "frontload_taper_metric_conflict"]
    figs += ["frontload_horizon_taper%s"
             % ("" if h == HORIZON_DAYS else "_%dd" % h)
             for h in taper_horizons]
    for f in figs:
        print("  Wrote %s/%s.png" % (FIG_DIR, f))

    return pd.concat([df_a] + [frames[h] for h in sorted(frames)],
                     ignore_index=True, sort=False)


if __name__ == "__main__":
    run()
