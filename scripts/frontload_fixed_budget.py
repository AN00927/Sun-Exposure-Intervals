# ---------------------------------------------------------------------------
# Horizon-derived quantities
#
# Everything the sweep needs that depends on the horizon is derived HERE, from
# a horizon passed in as an argument. Nothing rebinds `HORIZON_DAYS` and nothing
# touches `vitd_analyses.PROTOCOL_DAYS`.
# ---------------------------------------------------------------------------
def n_weeks(horizon_days: int) -> int:
    """Whole weeks in the horizon -- the multiplier from weekly to total SED."""
    return int(horizon_days) // 7


def session_grid(horizon_days: int) -> Tuple[int, ...]:
    """Arm (b) session counts for this horizon, from sessions-per-week."""
    w = n_weeks(horizon_days)
    return tuple(int(round(k * w)) for k in TAPER_SESSIONS_PER_WEEK)


def ref_n_sessions(horizon_days: int) -> int:
    """The arm (b) reference schedule's session count for this horizon."""
    return int(round(REF_SESSIONS_PER_WEEK * n_weeks(horizon_days)))


# ---------------------------------------------------------------------------
# Schedule builders
# ---------------------------------------------------------------------------
def within_week_schedule(weekly_sed: float, n_per_week: int,
                         horizon_days: int = HORIZON_DAYS
                         ) -> List[Tuple[float, float]]:
    """Weekly budget spread over `n_per_week` evenly-placed days, repeating.

    No erythema clipping: the budget must be conserved for the comparison to
    mean anything. Feasibility is reported downstream, not enforced here.
    """
    if n_per_week <= 0:
        return []
    offsets = sorted({int(round(i * 7.0 / n_per_week)) % 7
                      for i in range(n_per_week)})
    sed = float(weekly_sed) / len(offsets)
    return [(float(w * 7 + o), sed)
            for w in range(int(np.ceil(horizon_days / 7)) + 1)
            for o in offsets
            if w * 7 + o < horizon_days]


def _shape_grid() -> List[Dict]:
    """The (family, shape-parameter) grid for arm (b). Deterministic."""
    shapes: List[Dict] = [{"family": "uniform", "p1": np.nan, "p2": np.nan,
                           "shape_label": "flat"}]
    for r in TWO_PHASE_RATIOS:
        for f in TWO_PHASE_SWITCH_FRACS:
            shapes.append({"family": "two_phase", "p1": r, "p2": f,
                           "shape_label": "load x%g to %.0f%%T" % (r, 100 * f)})
    for r in EXP_RATIOS:
        for tau in EXP_TAUS_DAYS:
            shapes.append({"family": "exponential", "p1": r, "p2": tau,
                           "shape_label": "exp r=%g tau=%gd" % (r, tau)})
    return shapes


def _raw_profile(days: np.ndarray, shape: Dict,
                 horizon_days: int) -> np.ndarray:
    fam = shape["family"]
    if fam == "uniform":
        return dose_uniform(days, 1.0)
    if fam == "two_phase":
        return dose_two_phase(days, float(shape["p1"]), 1.0,
                              float(shape["p2"]) * horizon_days)
    if fam == "exponential":
        return dose_exponential(days, 1.0, float(shape["p1"]),
                                float(shape["p2"]))
    raise ValueError("unknown dose family %r" % (fam,))


def taper_schedule(total_sed: float, n_sessions: int, gamma: float,
                   shape: Dict, horizon_days: int = HORIZON_DAYS
                   ) -> List[Tuple[float, float]]:
    """Fixed-total schedule: spacing warped by `gamma`, dose shaped, rescaled.

    `build_variable_schedule` is called with `fst=None` so it does NOT clip to
    the erythema ceiling -- clipping would destroy the fixed budget the whole
    comparison rests on.
    """
    days = warp_days(n_sessions, horizon_days, gamma)
    raw = np.asarray(_raw_profile(days, shape, horizon_days), dtype=float)
    raw = np.clip(np.nan_to_num(raw, nan=0.0, posinf=0.0, neginf=0.0), 0.0, None)
    tot = float(raw.sum())
    if tot <= 0:
        return []
    seds = raw * (float(total_sed) / tot)
    return build_variable_schedule(days, seds, fst=None)


# ---------------------------------------------------------------------------
# Outcome extraction
# ---------------------------------------------------------------------------
def _time_to_sufficiency(res) -> float:
    t = np.asarray(res["t"])
    D = np.asarray(res["D"])
    idx = np.flatnonzero(D >= SUFFICIENCY_NMOL_L)
    return float(t[idx[0]]) if idx.size else float("nan")


def _geometry(schedule: Sequence[Tuple[float, float]],
              horizon_days: int) -> Dict:
    """Where the sessions actually sit in time.

    Reported because a spacing exponent can "win" on a terminal metric purely
    by leaving the front of the horizon empty and crowding sessions next to
    the measurement window. `max_gap_days` and `first_gap_days` make that
    visible instead of leaving it to be inferred from the exponent.
    """
    if not schedule:
        return {"max_gap_days": float(horizon_days), "first_gap_days":
                float(horizon_days), "sessions_in_final_28d": 0}
    days = np.sort(np.array([d for d, _s in schedule], dtype=float))
    edges = np.concatenate(([0.0], days, [float(horizon_days)]))
    gaps = np.diff(edges)
    return {"max_gap_days": float(gaps.max()),
            "first_gap_days": float(gaps[1] if gaps.size > 1 else gaps[0]),
            "sessions_in_final_28d": int((days >= horizon_days - 28).sum())}


def _safety(schedule: Sequence[Tuple[float, float]], fst: int) -> Dict:
    """Max single-session dose as a fraction of MED, plus feasibility flags."""
    if not schedule:
        side = compute_safety_sidecar(0.0, fst)
        return {"max_session_SED": 0.0, "max_frac_MED": 0.0, "worst_7d_SED": 0.0,
                "med_sed": float(side["individual_med_sed"]),
                "cpd_risk_level": side["cpd_risk_level"],
                "chronic_risk_level": side["chronic_risk_level"],
                "sub_erythemal": True, "burn": False}
    days = np.array([d for d, _s in schedule], dtype=float)
    seds = np.array([s for _d, s in schedule], dtype=float)
    max_sed = float(seds.max())
    worst_7d = 0.0
    for d0 in days:
        worst_7d = max(worst_7d,
                       float(seds[(days >= d0) & (days < d0 + 7.0)].sum()))
    side = compute_safety_sidecar(max_sed, fst, accumulated_sed_7d=worst_7d)
    frac = float(side["fraction_med"])
    return {"max_session_SED": max_sed,
            "max_frac_MED": frac,
            "worst_7d_SED": worst_7d,
            "med_sed": float(side["individual_med_sed"]),
            "cpd_risk_level": side["cpd_risk_level"],
            "chronic_risk_level": side["chronic_risk_level"],
            "sub_erythemal": bool(frac <= GAMMA_MED),
            "burn": bool(frac > 1.0)}


def _evaluate(rung: str, fst: int, schedule, params: Optional[ModelParams],
              horizon_days: int = HORIZON_DAYS) -> Dict:
    res = simulate_rung(rung, fst, list(schedule), int(horizon_days),
                        params=params)
    D = np.asarray(res["D"])
    t = np.asarray(res["t"])
    row = {
        "rung": rung,
        "rung_label": rung_label(rung),
        "FST": fst,
        "horizon_days": int(horizon_days),
        "n_sessions_total": len(schedule),
        "cumulative_SED": float(res["cumulative_SED"]),
        "steady_state_D": steady_state_D(res),
        "final_D": final_D(res),
        "AUC_above_sufficiency": (auc_above_sufficiency_per_SED(
            res, SUFFICIENCY_NMOL_L) * float(res["cumulative_SED"])),
        "AUC_deficit_below_sufficiency": auc_deficit(D, t, SUFFICIENCY_NMOL_L),
        "AUC_deficit_below_deficiency": auc_deficit(D, t, DEFICIENCY_NMOL_L),
        "days_to_sufficiency": _time_to_sufficiency(res),
        "reached_sufficiency": bool(np.any(D >= SUFFICIENCY_NMOL_L)),
    }
    row.update(_geometry(schedule, horizon_days))
    row.update(_safety(schedule, fst))
    if reports_risk(rung):
        cr = res.get("cancer_risk", {}) or {}
        for k in ("scc_index", "intermittent_index", "burn_fraction",
                  "combined_index"):
            row["risk_" + k] = cr.get(k, np.nan)
    return row


# ---------------------------------------------------------------------------
# ARM (a): within-week concentration
# ---------------------------------------------------------------------------
def sweep_within_week(params: Optional[ModelParams] = None,
                      horizon_days: int = HORIZON_DAYS) -> pd.DataFrame:
    rows: List[Dict] = []
    for fst in FSTS:
        for budget in WEEKLY_BUDGETS_SED:
            for n in SESSIONS_PER_WEEK:
                sched = within_week_schedule(budget, n, horizon_days)
                for rung in list_rungs():
                    row = _evaluate(rung, fst, sched, params, horizon_days)
                    row.update({
                        "arm": "within_week",
                        "weekly_budget_SED": budget,
                        "sessions_per_week": n,
                        "sed_per_session": budget / n,
                        "light_skin_contrast": fst == LIGHT_SKIN_CONTRAST_FST,
                    })
                    rows.append(row)
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# ARM (b): across-horizon taper
# ---------------------------------------------------------------------------
def sweep_horizon_taper(params: Optional[ModelParams] = None,
                        horizon_days: int = HORIZON_DAYS) -> pd.DataFrame:
    shapes = _shape_grid()
    grid = session_grid(horizon_days)
    weeks = n_weeks(horizon_days)
    rows: List[Dict] = []
    for fst in FSTS:
        for budget in WEEKLY_BUDGETS_SED:
            total = budget * weeks
            for n_sess in grid:
                for gamma in GAMMA_GRID:
                    for shape in shapes:
                        sched = taper_schedule(total, n_sess, gamma, shape,
                                               horizon_days)
                        if not sched:
                            continue
                        for rung in list_rungs():
                            row = _evaluate(rung, fst, sched, params,
                                            horizon_days)
                            row.update({
                                "arm": "horizon_taper",
                                "weekly_budget_SED": budget,
                                "total_budget_SED": total,
                                "n_sessions_planned": n_sess,
                                "sessions_per_week_equiv": n_sess / weeks,
                                "gamma": gamma,
                                "family": shape["family"],
                                "shape_p1": shape["p1"],
                                "shape_p2": shape["p2"],
                                "shape_label": shape["shape_label"],
                                "light_skin_contrast":
                                    fst == LIGHT_SKIN_CONTRAST_FST,
                            })
                            rows.append(row)
    return pd.DataFrame(rows)


