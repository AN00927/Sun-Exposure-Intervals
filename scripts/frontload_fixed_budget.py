def _plot_horizon_taper(df: pd.DataFrame,
                        horizon_days: int = HORIZON_DAYS,
                        suffix: str = "") -> None:
    """Arm (b) taper sweep, plotted on the PRIMARY metric.

    Solid traces are the deficiency burden below sufficiency, inverted so that
    up is better, referenced to the flat + uniformly-spaced arm at the same N.
    The thin dashed trace is the SECONDARY plateau measure, kept on the same
    axis so the two can be read against each other and neither can be quoted
    without the other.
    """
    rungs = list_rungs()
    budget = WEEKLY_BUDGETS_SED[len(WEEKLY_BUDGETS_SED) // 2]
    n_sess = ref_n_sessions(horizon_days)
    fig, axes = plt.subplots(len(FSTS), len(rungs),
                             figsize=(4.4 * len(rungs), 3.4 * len(FSTS)),
                             squeeze=False, sharex=True)
    for i, fst in enumerate(FSTS):
        for j, rung in enumerate(rungs):
            ax = axes[i][j]
            base = df[(df["FST"] == fst) & (df["rung"] == rung) &
                      (df["weekly_budget_SED"] == budget) &
                      (df["n_sessions_planned"] == n_sess)]
            if base.empty:
                continue
            ref_rows = base[(base["family"] == "uniform") &
                            np.isclose(base["gamma"], 1.0)]
            if ref_rows.empty:
                continue
            ref_def = max(float(ref_rows[PRIMARY_METRIC].iloc[0]), 1e-9)
            ref_ss = float(ref_rows[SECONDARY_METRIC].iloc[0])
            for fam in ("uniform", "two_phase", "exponential"):
                sub = base[base["family"] == fam]
                if sub.empty:
                    continue
                g = np.array(sorted(sub["gamma"].unique()))
                best, worst, infeas = [], [], []
                for gg in g:
                    cell = sub[np.isclose(sub["gamma"], gg)].sort_values(
                        PRIMARY_METRIC)
                    # PRIMARY is minimised, so "best" is the smallest deficit
                    best.append(float(cell[PRIMARY_METRIC].iloc[0]))
                    worst.append(float(cell[PRIMARY_METRIC].iloc[-1]))
                    infeas.append(not bool(cell["sub_erythemal"].iloc[0]))
                # inverted: positive = less deficiency than flat + uniform
                yb = 100.0 * (1.0 - np.array(best) / ref_def)
                yw = 100.0 * (1.0 - np.array(worst) / ref_def)
                infeas = np.array(infeas)
                ax.fill_between(g, yw, yb, color=FAMILY_COLORS[fam],
                                alpha=0.18, lw=0)
                ax.plot(g, yb, "o-", ms=4, lw=1.8, color=FAMILY_COLORS[fam],
                        label="%s (best shape)" % fam)
                if infeas.any():
                    ax.plot(g[infeas], yb[infeas], "x", color="k", ms=9, mew=2,
                            zorder=6)
            # SECONDARY: the plateau, retained on the same axis and labelled
            flat = base[base["family"] == "uniform"].sort_values("gamma")
            if not flat.empty:
                ax.plot(flat["gamma"].values,
                        100.0 * (flat[SECONDARY_METRIC].values / ref_ss - 1),
                        "--", color="#555555", lw=1.3, dashes=(4, 2),
                        label="plateau D_ss (SECONDARY, terminal)")
            ax.axvline(1.0, color="grey", lw=0.8, ls="--")
            ax.axhline(0.0, color="grey", lw=0.8, ls="--")
            ax.grid(alpha=0.3)
            ax.set_title("%s | %s" % (_fst_title(fst), rung_label(rung)),
                         fontsize=10)
            if i == len(FSTS) - 1:
                ax.set_xlabel("gamma  (<1 back-loaded, 1 uniform, "
                              ">1 front-loaded)")
            if j == 0:
                ax.set_ylabel("% better than flat, uniform\n"
                              "(PRIMARY: deficiency burden)")
    axes[0][0].legend(fontsize=7)
    fig.suptitle("ARM (b) across-horizon taper, PRIMARY metric: total SED "
                 "fixed at %g SED over %d d, %d sessions."
                 % (budget * n_weeks(horizon_days), horizon_days, n_sess)
                 + "\n" +
                 "Solid = deficiency burden below sufficiency, inverted so up "
                 "is better. Band = spread across shapes within the family."
                 + "\n" +
                 "Dashed grey = plateau D_ss (SECONDARY). Black x = best "
                 "shape breaches the sub-erythemal ceiling (INFEASIBLE).",
                 fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig("%s/frontload_horizon_taper%s.png" % (FIG_DIR, suffix), dpi=130)
    plt.close(fig)


def _plot_safety(df_a: pd.DataFrame, df_b: pd.DataFrame,
                 horizon_days: int = HORIZON_DAYS) -> None:
    """The decisive constraint: peak single-session dose as a fraction of MED."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.4))
