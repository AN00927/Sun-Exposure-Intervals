#      relative to the horizon -- they agree in 108/108 cells at 365 d versus
#      3/108 at 84 d. That agreement is CO-MOVEMENT, not corroboration: both
#      are terminal measures, so both reward whatever sits nearest the
#      endpoint. What wins them at 365 d is maximal back-loading, a schedule
#      that opens with a ~48-day gap of no exposure and stacks dose under the
#      measurement window. A metric winnable that way is not measuring
#      schedule quality.
#
#   2. Repo precedent. `vitd_objectives.OBJECTIVE_HIERARCHY` already fixes the
#      PRIMARY objective as reaching 50 nmol/L and then HOLDING it. Deficit
#      AUC and time-to-sufficiency sit far closer to that framing than a
#      terminal plateau does, so ranking arm (b) this way makes it consistent
#      with the hierarchy the repo already committed to rather than
#      introducing a new preference of this script's own.
#
# The plateau is NOT deleted or hidden -- it is reported alongside every
# primary number, carrying the co-movement warning, so the earlier
# plateau-ranked framing stays reproducible and this change is auditable.
