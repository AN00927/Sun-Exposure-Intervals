HORIZON_DAYS = PROTOCOL_DAYS          # match RESULTS.md section 5 protocol

# Arm (b) is re-run at a longer horizon as well. At 84 d the three-parameter
# dose families barely have room to express a shape, so a null taper result at
# 84 d alone invites the rebuttal "you did not give the shape families room to
# work". Running the same deterministic grid at 365 d forecloses it. Arm (a) is
# NOT re-run: its mechanism is per-session saturation, which is horizon
# insensitive, so a second horizon would only cost time.
TAPER_HORIZONS: Tuple[int, ...] = (84, 365)

# Skin types. FST V and VI are the PRIORITY population for this repo; FST II is
# carried only as an explicitly-labelled light-skin contrast.
