def _summarise_taper(df_b: pd.DataFrame,
                     horizon_days: int = HORIZON_DAYS) -> None:
    """Arm (b), ranked on the PRIMARY metric (deficit AUC below sufficiency).

    The plateau measure is printed alongside as a SECONDARY, with the
    co-movement warning, so the earlier plateau-ranked framing stays
    reproducible and the change of ranking metric is auditable rather than
    silent. See RANKING_METRIC_NOTE for why the primary is what it is.
    """
    ref_n = ref_n_sessions(horizon_days)
    grid = session_grid(horizon_days)
    print()
    print("=" * 78)
    print("ARM (b)  ACROSS-HORIZON TAPER -- fixed TOTAL SED over the horizon "
          "(%d d)" % horizon_days)
    print("PRIMARY metric: %s (minimise).  SECONDARY: %s (maximise)."
          % (PRIMARY_METRIC, SECONDARY_METRIC))
    print("=" * 78)
    for rung in list_rungs():
        print()
        print("  rung: %s (%s)" % (rung_label(rung), rung))
        for fst in FSTS:
            for budget in WEEKLY_BUDGETS_SED:
                base = df_b[(df_b["rung"] == rung) & (df_b["FST"] == fst) &
                            (df_b["weekly_budget_SED"] == budget)]
                if base.empty:
                    continue
                ref_rows = base[(base["family"] == "uniform") &
                                np.isclose(base["gamma"], 1.0) &
                                (base["n_sessions_planned"] == ref_n)]
                if ref_rows.empty:
                    continue
                ref_def = max(float(ref_rows[PRIMARY_METRIC].iloc[0]), 1e-9)
                ref_ss = float(ref_rows[SECONDARY_METRIC].iloc[0])
                feas = base[base["sub_erythemal"].astype(bool)]
                print("    %-28s %5g SED/wk | flat+uniform ref (N=%d): "
                      "deficit=%.0f nmol/L.d, D_ss=%.2f"
                      % (_fst_title(fst), budget, ref_n, ref_def, ref_ss))

                # ---- PRIMARY ranking: least time-integrated deficiency ----
                b = base.loc[base[PRIMARY_METRIC].idxmin()]
                print("      PRIMARY  best by deficit: %s / %s gamma=%.1f "
                      "N=%d -> deficit=%.0f (%+.1f%%), to-suff %s, "
                      "peak %.0f%% MED%s"
                      % (b["family"], b["shape_label"], b["gamma"],
                         int(b["n_sessions_planned"]), b[PRIMARY_METRIC],
                         100 * (b[PRIMARY_METRIC] / ref_def - 1),
                         _fmt_days(b["days_to_sufficiency"]),
                         100 * b["max_frac_MED"], _flag(b)))
                if feas.empty:
                    print("      PRIMARY  NO sub-erythemal arm exists at this "
                          "budget/FST -- the budget itself is infeasible")
                else:
                    bf = feas.loc[feas[PRIMARY_METRIC].idxmin()]
                    print("      PRIMARY  sub-erythemal best: %s / %s "
                          "gamma=%.1f N=%d -> deficit=%.0f (%+.1f%%), "
                          "to-suff %s, peak %.0f%% MED"
                          % (bf["family"], bf["shape_label"], bf["gamma"],
                             int(bf["n_sessions_planned"]), bf[PRIMARY_METRIC],
                             100 * (bf[PRIMARY_METRIC] / ref_def - 1),
                             _fmt_days(bf["days_to_sufficiency"]),
                             100 * bf["max_frac_MED"]))

                # ---- SECONDARY: the plateau, retained and flagged ----
                b2 = base.loc[base[SECONDARY_METRIC].idxmax()]
                print("      2ndary   best by plateau D_ss: %s / %s "
                      "gamma=%.1f N=%d -> D_ss=%.2f (%+.2f%%)%s"
                      % (b2["family"], b2["shape_label"], b2["gamma"],
                         int(b2["n_sessions_planned"]), b2[SECONDARY_METRIC],
                         100 * (b2[SECONDARY_METRIC] / ref_ss - 1), _flag(b2)))
                if float(b2["gamma"]) < 1.0:
                    print("               ^ BACK-loaded winner: this is a "
                          "TERMINAL-METRIC ARTEFACT, not a schedule.")
                    print("                 It opens with a %.0f-day gap and "
                          "reaches sufficiency %s; deficit %.0f vs %.0f for "
                          "flat+uniform."
                          % (b2["first_gap_days"],
                             _fmt_days(b2["days_to_sufficiency"]),
                             b2[PRIMARY_METRIC], ref_def))

                # ---- matched-N deconfounding, on the PRIMARY metric ----
                # The grid maximum mixes session COUNT (how finely the fixed
                # total is chopped) with PROFILE SHAPE/SPACING (the actual
                # front-loading question). Re-reference to flat + uniform at
                # the SAME N so only shape and spacing remain.
                for n_sess in grid:
                    at_n = base[base["n_sessions_planned"] == n_sess]
                    r_n = at_n[(at_n["family"] == "uniform") &
                               np.isclose(at_n["gamma"], 1.0)]
                    if at_n.empty or r_n.empty:
                        continue
                    # Deliberately NOT named ref_n: an earlier version of this
                    # loop shadowed the session-count ref_n with a metric
                    # value, which silently disabled the block below it.
                    rd = max(float(r_n[PRIMARY_METRIC].iloc[0]), 1e-9)
                    rs = float(r_n[SECONDARY_METRIC].iloc[0])
                    bn = at_n.loc[at_n[PRIMARY_METRIC].idxmin()]
                    fwd = at_n[at_n["gamma"] >= 1.0]
                    ss_fwd = (100 * (fwd[SECONDARY_METRIC].max() / rs - 1)
                              if not fwd.empty else float("nan"))
                    print("      N=%-4d deficit %+.1f%% (best: %s gamma=%.1f)"
                          "  |  plateau D_ss %+.2f%% (front-loaded half "
                          "only)%s"
                          % (n_sess, 100 * (bn[PRIMARY_METRIC] / rd - 1),
                             bn["shape_label"], bn["gamma"], ss_fwd,
                             _flag(bn)))

                # ---- metric sensitivity across gamma, flat dose ----
                flat = base[(base["family"] == "uniform") &
                            (base["n_sessions_planned"] == ref_n)
                            ].sort_values("gamma")
                if not flat.empty:
                    g_ss = float(flat.loc[flat[SECONDARY_METRIC].idxmax(),
                                          "gamma"])
                    g_fin = float(flat.loc[flat["final_D"].idxmax(), "gamma"])
                    g_def = float(flat.loc[flat[PRIMARY_METRIC].idxmin(),
                                           "gamma"])
                    print("      argmax gamma: %.1f by deficit (PRIMARY) | "
                          "%.1f by D_ss, %.1f by final D (both TERMINAL, "
                          "co-moving)" % (g_def, g_ss, g_fin))


