def _fmt_gammas(vals) -> str:
    """Gamma values as a plain list, without numpy repr noise."""
    out = sorted(float(v) for v in vals)
    return "[" + ", ".join("%.1f" % v for v in out) + "]"


def _fmt_days(v) -> str:
    """Days-to-sufficiency for printing; NaN means it never got there."""
    v = float(v)
    return ("day %.0f" % v) if np.isfinite(v) else "NEVER"


def _flag(row) -> str:
    if bool(row["burn"]):
        return "  *** OVERDOSE ***"
    if not bool(row["sub_erythemal"]):
        return "  [INFEASIBLE > ceiling]"
    return ""


