# Arm (a): how many days of the week carry the budget.
SESSIONS_PER_WEEK: Tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7)

# Arm (b): spacing warp and session counts over the whole horizon. The session
# grid is expressed as sessions PER WEEK and scaled to the horizon, so the same
# behavioural schedules (1, 2, 3 and 7 outings a week) are compared at every
