def _plot_metric_conflict(frames: Dict[int, pd.DataFrame]) -> None:
    """Terminal vs horizon-integrated metrics, as a function of the spacing
    exponent, at each horizon.

    This figure exists because the two camps of outcome disagree about the
    SIGN of the taper, and the disagreement widens with the horizon. Plotting
    them on one panel stops either camp being quoted on its own.
    """
    horizons = sorted(frames)
    fig, axes = plt.subplots(1, len(horizons), figsize=(6.0 * len(horizons), 4.6),
                             squeeze=False)
    fst, rung = 5, "melanin_only"
    budget = WEEKLY_BUDGETS_SED[len(WEEKLY_BUDGETS_SED) // 2]
    for k, horizon in enumerate(horizons):
        ax = axes[0][k]
        df = frames[horizon]
        n_sess = ref_n_sessions(horizon)
        sub = df[(df["FST"] == fst) & (df["rung"] == rung) &
                 (df["weekly_budget_SED"] == budget) &
                 (df["n_sessions_planned"] == n_sess) &
                 (df["family"] == "uniform")].sort_values("gamma")
        if sub.empty:
            continue
        g = sub["gamma"].values
        ref = sub[np.isclose(sub["gamma"], 1.0)].iloc[0]
        ax.plot(g, 100 * (sub["steady_state_D"].values /
                          float(ref["steady_state_D"]) - 1),
                "o-", color="#1f77b4", lw=2, ms=5,
                label="steady-state 25(OH)D  (TERMINAL: last 28 d)")
        ax.plot(g, 100 * (sub["final_D"].values /
                          float(ref["final_D"]) - 1),
                "s--", color="#17becf", lw=1.6, ms=4,
                label="final 25(OH)D  (TERMINAL: endpoint)")
        ax.plot(g, -100 * (sub["AUC_deficit_below_sufficiency"].values /
                           max(float(ref["AUC_deficit_below_sufficiency"]), 1e-9)
                           - 1),
                "^-", color="#d62728", lw=2, ms=5,
                label="deficit below sufficiency, INVERTED "
                      "(INTEGRATED: whole horizon)")
        ax.axhline(0.0, color="grey", lw=0.8, ls="--")
        ax.axvline(1.0, color="grey", lw=0.8, ls="--")
        ax.grid(alpha=0.3)
        ax.set_xlabel("gamma  (<1 back-loaded, 1 uniform, >1 front-loaded)")
        ax.set_ylabel("% better than flat, uniform spacing")
        ax.set_title("horizon = %d d   (FST V, melanin_only, %g SED/wk, N=%d)"
                     % (horizon, budget, n_sess), fontsize=10)
        # annotate what the terminal-metric winner actually is as a schedule
        worst = sub.iloc[int(np.argmin(sub["gamma"].values))]
        tts = float(worst["days_to_sufficiency"])
        tts_txt = ("day %.0f" % tts) if np.isfinite(tts) else "no point in the run"
        ax.annotate("gamma=%.1f opens with a %.0f-day\ngap and reaches "
                    "sufficiency\nat %s"
                    % (worst["gamma"], worst["first_gap_days"], tts_txt),
                    xy=(float(worst["gamma"]), 0), xycoords="data",
                    xytext=(0.04, 0.06), textcoords="axes fraction",
                    fontsize=8, color="#8b0000",
                    bbox=dict(boxstyle="round", fc="#fff3f3", ec="#d62728",
                              lw=0.8))
        if k == 0:
            ax.legend(fontsize=7, loc="upper right")
    fig.suptitle("ARM (b) METRIC CONFLICT: terminal and horizon-integrated "
                 "outcomes disagree on the SIGN of the taper,\nand the "
                 "disagreement widens with the horizon. Neither camp may be "
                 "quoted without the other.", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.90))
    fig.savefig("%s/frontload_taper_metric_conflict.png" % FIG_DIR, dpi=130)
    plt.close(fig)


def taper_horizon_comparison(frames: Dict[int, pd.DataFrame]) -> pd.DataFrame:
    """Matched-N taper leverage at each horizon, side by side.

    For every (rung, FST, budget, N) cell the reference is the flat,
    uniformly-spaced arm AT THE SAME N, so the session-count effect -- which
    dominates the raw grid maximum and grows with the horizon -- is divided
    out and only shape and spacing remain. This table is the direct answer to
    "does the taper null survive a longer horizon?".

    Also records whether the steady-state and endpoint metrics agree on the
    SIGN of the spacing exponent, which is the second thing the longer horizon
    was run to settle.
    """
    rows: List[Dict] = []
    for horizon, df in sorted(frames.items()):
        for (rung, fst, budget, n_sess), g in df.groupby(
                ["rung", "FST", "weekly_budget_SED", "n_sessions_planned"]):
            ref_rows = g[(g["family"] == "uniform") &
                         np.isclose(g["gamma"], 1.0)]
            if ref_rows.empty:
                continue
            ref = float(ref_rows["steady_state_D"].iloc[0])
            flat = g[g["family"] == "uniform"]
            feas = g[g["sub_erythemal"].astype(bool)]
            back = flat[np.isclose(flat["gamma"], min(GAMMA_GRID))]
            fwd = g[g["gamma"] >= 1.0]          # front-loaded half only
            ref_def = max(float(
                ref_rows["AUC_deficit_below_sufficiency"].iloc[0]), 1e-9)
            rows.append({
                "horizon_days": horizon,
                "rung": rung,
                "FST": fst,
                "weekly_budget_SED": budget,
                "n_sessions_planned": n_sess,
                "ref_flat_uniform_D_ss": ref,
                "best_gain_pct": 100.0 * (g["steady_state_D"].max() / ref - 1),
                "best_gain_pct_feasible": (
                    100.0 * (feas["steady_state_D"].max() / ref - 1)
                    if not feas.empty else np.nan),
                "spacing_only_gain_pct": 100.0 * (flat["steady_state_D"].max()
                                                  / ref - 1),
                "backload_loss_pct": (
                    100.0 * (float(back["steady_state_D"].iloc[0]) / ref - 1)
                    if not back.empty else np.nan),
                "argmax_gamma_D_ss": float(
                    flat.loc[flat["steady_state_D"].idxmax(), "gamma"]),
                "argmax_gamma_final_D": float(
                    flat.loc[flat["final_D"].idxmax(), "gamma"]),
                "argmax_gamma_min_deficit": float(flat.loc[
                    flat["AUC_deficit_below_sufficiency"].idxmin(), "gamma"]),
                "max_frac_MED_at_best": float(
                    g.loc[g["steady_state_D"].idxmax(), "max_frac_MED"]),
                # Plateau gain with the BACK-loaded half of the grid excluded.
                # At a long horizon the raw maximum is won by extreme
                # back-loading purely as a measurement-window artefact, so this
                # is the honest "does front-loading raise the plateau?" number.
                "frontload_only_gain_pct": (
                    100.0 * (fwd["steady_state_D"].max() / ref - 1)
                    if not fwd.empty else np.nan),
                # --- the horizon-INTEGRATED camp, for the metric conflict ---
                "ref_deficit": float(
                    ref_rows["AUC_deficit_below_sufficiency"].iloc[0]),
                "best_deficit_drop_pct": 100.0 * (
                    1.0 - flat["AUC_deficit_below_sufficiency"].min()
                    / ref_def),
                "best_deficit_drop_pct_allshapes": 100.0 * (
                    1.0 - g["AUC_deficit_below_sufficiency"].min() / ref_def),
                "best_deficit_drop_pct_feasible": (
                    100.0 * (1.0 - feas["AUC_deficit_below_sufficiency"].min()
                             / ref_def) if not feas.empty else np.nan),
                "argmax_gamma_min_deficit_feasible": (
                    float(feas.loc[feas["AUC_deficit_below_sufficiency"]
                                   .idxmin(), "gamma"])
                    if not feas.empty else np.nan),
                "deficit_at_argmax_D_ss": float(
                    flat.loc[flat["steady_state_D"].idxmax(),
                             "AUC_deficit_below_sufficiency"]),
                "days_to_suff_at_argmax_D_ss": float(
                    flat.loc[flat["steady_state_D"].idxmax(),
                             "days_to_sufficiency"]),
                "days_to_suff_at_argmax_deficit": float(
                    flat.loc[flat["AUC_deficit_below_sufficiency"].idxmin(),
                             "days_to_sufficiency"]),
                "max_gap_at_argmax_D_ss": float(
                    flat.loc[flat["steady_state_D"].idxmax(), "max_gap_days"]),
                "first_gap_at_argmax_D_ss": float(
                    flat.loc[flat["steady_state_D"].idxmax(),
                             "first_gap_days"]),
            })
    out = pd.DataFrame(rows)
    if not out.empty:
        # Do the two metrics agree on the DIRECTION of the spacing exponent?
        out["metrics_agree_on_sign"] = (
            np.sign(out["argmax_gamma_D_ss"] - 1.0) ==
            np.sign(out["argmax_gamma_final_D"] - 1.0))
    return out


def _summarise_horizon_comparison(cmp_df: pd.DataFrame) -> None:
    """Both horizons side by side, led by the PRIMARY metric.

    Order is deliberate: the transient result is the conclusion, the plateau
    null is the finding that survives the longer horizon, and the back-loading
    artefact is documented with the numbers that expose it so it can never be
    quoted bare.
    """
    if cmp_df.empty:
        return
    print()
    print("=" * 78)
    print("ARM (b) CONCLUSION")
    print("=" * 78)
    print("  " + ARM_B_CONCLUSION)
    print()
    print("  " + RANKING_METRIC_NOTE)
    print()
    print("  Matched-N throughout: every arm is referenced to flat + uniform")
    print("  spacing at the SAME session count, so the session-count effect")
    print("  is divided out and only shape and spacing remain.")
    print("=" * 78)
    for horizon, g in cmp_df.groupby("horizon_days"):
        print()
        print("  horizon = %d d  (%d cells)" % (horizon, len(g)))

        # ---- 1. PRIMARY: the transient. This is the headline. ----
        print("    [1] PRIMARY -- deficiency burden cut by front-loading "
              "(the RESULT):")
        for rung, gr in g.groupby("rung"):
            print("        %-20s mean %.1f%%  max %.1f%%   "
                  "(sub-erythemal only: mean %.1f%%)"
                  % (rung, gr["best_deficit_drop_pct_allshapes"].mean(),
                     gr["best_deficit_drop_pct_allshapes"].max(),
                     gr["best_deficit_drop_pct_feasible"].mean()))
        print("        argmax gamma by deficit: %s  |  sub-erythemal only: %s"
              % (_fmt_gammas(g["argmax_gamma_min_deficit"].unique()),
                 _fmt_gammas(g["argmax_gamma_min_deficit_feasible"].dropna()
                             .unique())))
        print("        days to sufficiency at the deficit optimum: %.1f "
              "(vs %.1f at the plateau optimum)"
              % (g["days_to_suff_at_argmax_deficit"].mean(),
                 g["days_to_suff_at_argmax_D_ss"].mean()))

        # ---- 2. the plateau NULL, kept prominent ----
        print("    [2] SECONDARY -- plateau (D_ss) gain from front-loading, "
              "gamma >= 1 (the NULL):")
        for rung, gr in g.groupby("rung"):
            print("        %-20s mean %+.2f%%  max %+.2f%%"
                  % (rung, gr["frontload_only_gain_pct"].mean(),
                     gr["frontload_only_gain_pct"].max()))
        print("        Front-loading does not raise the plateau. At 365 d it "
              "does not move it at all.")

        # ---- 3. the artefact, documented so it cannot be quoted bare ----
        raw_max = g["best_gain_pct"].max()
        backload_won = float((g["argmax_gamma_D_ss"] < 1.0).mean())
        print("    [3] ARTEFACT WARNING -- the raw plateau maximum over the "
              "whole grid is %+.1f%%." % raw_max)
        if backload_won > 0.5:
            print("        It is won by BACK-loading in %.0f%% of cells and "
                  "is NOT a schedule result." % (100 * backload_won))
            print("        That arm opens with a %.0f-day gap (max gap "
                  "%.0f d), carries deficit %.0f nmol/L.d against %.0f for "
                  "flat+uniform,"
                  % (g["first_gap_at_argmax_D_ss"].mean(),
                     g["max_gap_at_argmax_D_ss"].mean(),
                     g["deficit_at_argmax_D_ss"].mean(),
                     g["ref_deficit"].mean()))
            print("        and reaches sufficiency on day %.0f against day "
                  "%.0f. It stacks dose under the measurement window."
                  % (g["days_to_suff_at_argmax_D_ss"].mean(),
                     g["days_to_suff_at_argmax_deficit"].mean()))
        else:
            print("        Back-loading wins the plateau in only %.0f%% of "
                  "cells at this horizon." % (100 * backload_won))

        # ---- 4. why the terminal metrics agreeing proves nothing ----
        agree = g["metrics_agree_on_sign"]
        print("    [4] METRIC SIGN CHECK: D_ss and final-D argmax gamma agree "
              "in %d/%d cells (%.0f%%)."
              % (int(agree.sum()), len(agree), 100.0 * agree.mean()))
        print("        Both are TERMINAL measures, so agreement is "
              "CO-MOVEMENT, not corroboration; as the averaging window")
        print("        shrinks against the horizon they collapse onto each "
              "other. The PRIMARY metric disagrees with both.")
        print("        argmax gamma -- deficit %s | D_ss %s | final D %s"
              % (_fmt_gammas(g["argmax_gamma_min_deficit"].unique()),
                 _fmt_gammas(g["argmax_gamma_D_ss"].unique()),
                 _fmt_gammas(g["argmax_gamma_final_D"].unique())))

        # ---- 5. feasibility ----
        n_nofeas = int(g["best_deficit_drop_pct_feasible"].isna().sum())
        print("    [5] ERYTHEMA CAP: trims the deficit gain but never flips "
              "its direction.")
        if n_nofeas:
            print("        %d/%d cells have NO sub-erythemal arm at any "
                  "spacing -- the budget itself is infeasible there."
                  % (n_nofeas, len(g)))


