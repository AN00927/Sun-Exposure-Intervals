TWO_PHASE_RATIOS: Tuple[float, ...] = (1.5, 2.5, 4.0)     # load : maintenance
TWO_PHASE_SWITCH_FRACS: Tuple[float, ...] = (0.15, 0.30, 0.50)
EXP_RATIOS: Tuple[float, ...] = (0.5, 1.5, 4.0)           # initial overshoot
EXP_TAUS_DAYS: Tuple[float, ...] = (7.0, 21.0, 56.0)

